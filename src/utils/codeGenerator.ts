import { SplashProject } from '../types/splash';
import { buildTimelineSegments } from './flowEngine';

export function generateAndroidComposeCode(project: SplashProject): string {
  const { totalDurationMs } = buildTimelineSegments(project.flowStates);
  const logoLayer = project.layers.find(
    (l) => l.type === 'image-logo' || l.type === 'vector-emblem'
  );
  const titleLayer = project.layers.find((l) => l.type === 'text');
  const firstState = project.flowStates[0];
  const lastState = project.flowStates[project.flowStates.length - 1];

  const startScale =
    (logoLayer && firstState?.layerSnapshots[logoLayer.id]?.scaleX) ?? 0.4;
  const endScale =
    (logoLayer && lastState?.layerSnapshots[logoLayer.id]?.scaleX) ?? 1.0;

  const bgStart = project.background.gradientStart || project.background.solidColor;
  const bgEnd = project.background.gradientEnd || project.background.solidColor;

  return `// Android 15 Jetpack Compose + Core SplashScreen API
// Generated by Kinetix Splash Studio — Project: ${project.name}
// Total Flow Duration: ${totalDurationMs}ms (${project.flowStates.length} Figma Flow States)

package com.kinetix.splash

import androidx.compose.animation.core.*
import androidx.compose.foundation.background
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material3.Text
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.draw.alpha
import androidx.compose.ui.draw.clip
import androidx.compose.ui.draw.scale
import androidx.compose.ui.graphics.Brush
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.layout.ContentScale
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import coil.compose.AsyncImage
import kotlinx.coroutines.delay

@Composable
fun AnimatedSplashScreen(onSplashFinished: () -> Unit) {
    var currentStage by remember { mutableIntStateOf(0) }

    val logoScale by animateFloatAsState(
        targetValue = if (currentStage == 0) ${startScale}f else ${endScale}f,
        animationSpec = spring(
            dampingRatio = Spring.DampingRatioLowBouncy,
            stiffness = ${firstState?.transitionToNext.spring.stiffness || 300}f
        ),
        label = "logoScale"
    )

    val contentAlpha by animateFloatAsState(
        targetValue = if (currentStage == 0) 0f else 1f,
        animationSpec = tween(durationMillis = ${firstState?.transitionToNext.durationMs || 750}),
        label = "contentAlpha"
    )

    LaunchedEffect(Unit) {
        currentStage = 1
        delay(${totalDurationMs}L)
        onSplashFinished()
    }

    Box(
        modifier = Modifier
            .fillMaxSize()
            .background(
                Brush.linearGradient(
                    colors = listOf(
                        Color(0xFF${bgStart.replace('#', '')}),
                        Color(0xFF${bgEnd.replace('#', '')})
                    )
                )
            ),
        contentAlignment = Alignment.Center
    ) {
        Column(horizontalAlignment = Alignment.CenterHorizontally) {
            AsyncImage(
                model = "${logoLayer?.imageUrl || 'https://your-cdn.com/splash-icon.png'}",
                contentDescription = "${logoLayer?.name || 'Splash Icon'}",
                contentScale = ContentScale.Crop,
                modifier = Modifier
                    .size(${logoLayer?.width || 116}.dp)
                    .scale(logoScale)
                    .alpha(contentAlpha)
                    .clip(RoundedCornerShape(28.dp))
            )
            Spacer(modifier = Modifier.height(28.dp))
            Text(
                text = "${titleLayer?.text || project.name}",
                color = Color(0xFF${(titleLayer?.textColor || '#F8FAFC').replace('#', '')}),
                fontSize = ${titleLayer?.fontSize || 26}.sp,
                fontWeight = FontWeight.Bold,
                modifier = Modifier.alpha(contentAlpha)
            )
        }
    }
}`;
}

export function generateSwiftUICode(project: SplashProject): string {
  const { totalDurationMs } = buildTimelineSegments(project.flowStates);
  const logoLayer = project.layers.find(
    (l) => l.type === 'image-logo' || l.type === 'vector-emblem'
  );
  const titleLayer = project.layers.find((l) => l.type === 'text');
  const firstState = project.flowStates[0];
  const lastState = project.flowStates[project.flowStates.length - 1];

  const startScale =
    (logoLayer && firstState?.layerSnapshots[logoLayer.id]?.scaleX) ?? 0.4;
  const endScale =
    (logoLayer && lastState?.layerSnapshots[logoLayer.id]?.scaleX) ?? 1.0;

  const bgStart = project.background.gradientStart || project.background.solidColor;
  const bgEnd = project.background.gradientEnd || project.background.solidColor;

  return `// iOS 18 SwiftUI Smart Animate Launch View
// Generated by Kinetix Splash Studio — Project: ${project.name}
// Total Flow Duration: ${(totalDurationMs / 1000).toFixed(2)}s (${project.flowStates.length} Figma Flow States)

import SwiftUI

struct SplashScreenView: View {
    @State private var isActiveStage = false
    var onComplete: () -> Void

    var body: some View {
        ZStack {
            LinearGradient(
                colors: [
                    Color(hex: "${bgStart}"),
                    Color(hex: "${bgEnd}")
                ],
                startPoint: .topLeading,
                endPoint: .bottomTrailing
            )
            .ignoresSafeArea()

            VStack(spacing: 24) {
                AsyncImage(url: URL(string: "${logoLayer?.imageUrl || 'https://your-cdn.com/splash-logo.png'}")) { image in
                    image
                        .resizable()
                        .scaledToFill()
                } placeholder: {
                    RoundedRectangle(cornerRadius: 28, style: .continuous)
                        .fill(Color.white.opacity(0.08))
                }
                .frame(width: ${logoLayer?.width || 116}, height: ${logoLayer?.height || 116})
                .clipShape(RoundedRectangle(cornerRadius: 28, style: .continuous))
                .scaleEffect(isActiveStage ? ${endScale} : ${startScale})
                .opacity(isActiveStage ? 1.0 : 0.0)

                Text("${titleLayer?.text || project.name}")
                    .font(.system(size: ${titleLayer?.fontSize || 28}, weight: .bold, design: .default))
                    .tracking(${titleLayer?.letterSpacing || 2})
                    .foregroundStyle(Color(hex: "${titleLayer?.textColor || '#F8FAFC'}"))
                    .opacity(isActiveStage ? 1.0 : 0.0)
                    .offset(y: isActiveStage ? 0 : 24)
            }
        }
        .onAppear {
            withAnimation(.spring(response: 0.65, dampingFraction: 0.72)) {
                isActiveStage = true
            }
            DispatchQueue.main.asyncAfter(deadline: .now() + ${(totalDurationMs / 1000).toFixed(2)}) {
                onComplete()
            }
        }
    }
}`;
}
